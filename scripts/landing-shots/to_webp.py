"""
PNG captures (shots.mjs, 2x DPR) → WebP at 2x and 1x for the landing page, plus a module with their sizes so every
<img> has width/height. Empty margins (the email's) are trimmed.
  python3 scripts/landing-shots/to_webp.py <png-dir> frontend/public/landing frontend/src/pages/landing/shots.js
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageChops

src, out, module = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
out.mkdir(parents=True, exist_ok=True)
sizes = {}
for png in sorted(src.glob("*.png")):
    img = Image.open(png).convert("RGB")
    bg = Image.new("RGB", img.size, img.getpixel((img.width - 1, img.height - 1)))
    box = ImageChops.difference(img, bg).getbbox()
    if box and png.stem == "email":                      # the email: drop the empty canvas under it
        img = img.crop((0, 0, img.width, min(img.height, box[3] + 40)))
    name = png.stem
    img.save(out / f"{name}@2x.webp", "WEBP", quality=80, method=6)
    half = img.resize((img.width // 2, img.height // 2), Image.LANCZOS)
    half.save(out / f"{name}.webp", "WEBP", quality=82, method=6)
    sizes[name] = {"w": half.width, "h": half.height}
    kb = lambda p: (out / p).stat().st_size // 1024
    print(f"{name}: {half.width}x{half.height}  1x {kb(f'{name}.webp')} KB  2x {kb(f'{name}@2x.webp')} KB")
module.write_text("// Generated by scripts/landing-shots/to_webp.py: CSS-pixel sizes of the landing images (also served at 2x).\n"
                  f"export const SHOTS = {json.dumps(sizes, indent=2)}\n")
