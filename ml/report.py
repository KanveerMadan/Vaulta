def table(ev: dict, name: str, splits=FRESH) -> list[str]:
    rows = ["| Test set | Rows | System | Agreement | Macro-F1 | Covered agreement | Review rate |", "|---|---|---|---|---|---|---|"]
    for split, title in splits:
        e = ev.get(split)
        if not e or not e["rows"]:
            rows.append(f"| {title} | 0 | (no data) | | | | |")
            continue
        for key, label in (("rules", "Rules today"), ("known_merchant_only", "Known merchant on its own words, no model"),
                           ("model", f"{name} alone"), ("rules_then_model", f"Known merchant → {name} (shipped order)")):
            s = e[key]
            rows.append(f"| {title} | {e['rows']} | {label} | {pct(s['agreement'])} | {pts(s['macro_f1'])} | "
                        f"{pct(s['covered_agreement'])} | {pct(s['review_rate'])} |")
    return rows


